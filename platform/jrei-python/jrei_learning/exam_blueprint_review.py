"""Metadata-only scientific integrity screening for the existing JREI exam centre.

The PHP mother-DB remains authoritative for question rights, independent
item/key reviewers, orders, entitlements, learner consent, server timers and
grading. This module checks *declared* item evidence and blueprint coverage,
without seeing examination text, guessing correct answers or issuing a sale.
It can hold defective candidates, but cannot approve or publish any exam.
"""
from __future__ import annotations

import hashlib
import json
from collections import Counter
from typing import Literal

from pydantic import Field, model_validator
from jrei_core.contracts import Digest, Identifier, StrictContract


ExamLevel = Literal[
    "SCHOOL_01_12", "SCHOOL_FINAL", "IRAN_KONKUR",
    "MASTERS", "PHD", "INTERNATIONAL",
]
ExamPurpose = Literal["DIAGNOSTIC", "PROGRESS", "FINAL_MOCK", "PRACTICE"]
Rights = Literal["UNKNOWN", "PENDING", "ALLOWED", "RESTRICTED", "REVOKED"]


class ExamBlueprint(StrictContract):
    blueprint_id: Identifier
    revision_id: Identifier
    policy_sha256: Digest
    exam_level: ExamLevel
    purpose: ExamPurpose
    subject_code: Identifier
    language: Literal["fa", "en", "bi"]
    required_item_count: int = Field(ge=1, le=500)
    # A blueprint is an independently reviewed *target*, not a generated key.
    domain_required_counts: dict[Identifier, int] = Field(min_length=1, max_length=50)
    required_key_reviewers: int = Field(ge=1, le=5)
    require_original_items: bool = True
    requires_accommodation_review: bool = True

    @model_validator(mode="after")
    def validate_distribution(self) -> "ExamBlueprint":
        if any(count < 1 or count > self.required_item_count
               for count in self.domain_required_counts.values()):
            raise ValueError("BLUEPRINT_DOMAIN_COUNTS_OUT_OF_BOUNDS")
        if sum(self.domain_required_counts.values()) != self.required_item_count:
            raise ValueError("BLUEPRINT_DOMAIN_COUNTS_NOT_COMPLETE")
        return self


class ItemEvidence(StrictContract):
    item_id: Identifier
    item_revision: Identifier
    blueprint_id: Identifier
    blueprint_revision: Identifier
    domain_code: Identifier
    language: Literal["fa", "en"]
    item_stem_sha256: Digest
    option_sha256s: list[Digest] = Field(min_length=2, max_length=6)
    # Answer is an OPTION INDEX from a reviewed original source, never
    # generated by LLM text or guessed on behalf of a student.
    declared_key_index: int = Field(ge=0, le=5)
    answer_rationale_sha256: Digest | None = None
    item_source_id: Identifier
    item_source_version: Identifier
    source_content_sha256: Digest
    source_citation_anchor: Identifier
    source_rights_state: Rights = "UNKNOWN"
    source_version_current: bool = False
    source_withdrawn: bool = False
    independently_source_reviewed: bool = False
    independently_item_reviewed: bool = False
    independent_key_review_receipt_sha256s: list[Digest] = Field(default_factory=list, max_length=5)
    key_provenance_verified_by_original_authority: bool = False
    original_item: bool = False
    accommodation_reviewed: bool = False
    # Digest of candidate's key disclosure/answer rationale.
    # Full questions, learner responses, identities and payment data MUST
    # never appear in this metadata-only proposal.
    key_evidence_sha256: Digest | None = None

    @model_validator(mode="after")
    def check_key_and_proofs(self) -> "ItemEvidence":
        if len(set(self.option_sha256s)) != len(self.option_sha256s):
            raise ValueError("DUPLICATED_ANSWER_OPTIONS")
        if self.declared_key_index >= len(self.option_sha256s):
            raise ValueError("DECLARED_KEY_INDEX_OUT_OF_RANGE")
        if len(set(self.independent_key_review_receipt_sha256s)) != len(
            self.independent_key_review_receipt_sha256s
        ):
            raise ValueError("DUPLICATE_KEY_REVIEW_RECEIPT")
        if self.item_stem_sha256 in self.option_sha256s:
            raise ValueError("STEM_DIGEST_REUSED_AS_OPTION")
        return self


class ExamReviewRequest(StrictContract):
    schema_version: Literal["jr.jrei.exam-blueprint-review.v1"] = (
        "jr.jrei.exam-blueprint-review.v1"
    )
    policy_version: Identifier
    blueprint: ExamBlueprint
    items: list[ItemEvidence] = Field(max_length=500)
    # Declared approval metadata is *not* a reviewer signature.
    blueprint_independently_approved: bool = False
    exam_publication_authorized: Literal[False] = False

    @model_validator(mode="after")
    def unique_item_revisions(self) -> "ExamReviewRequest":
        if len({i.item_id for i in self.items}) != len(self.items):
            raise ValueError("DUPLICATE_ITEM_IN_EXAM")
        return self


class ItemIntegrityFinding(StrictContract):
    item_id: Identifier
    decision: Literal["HOLD", "CANDIDATE_FOR_OWNER_REVIEW"]
    reason_codes: list[str] = Field(min_length=1, max_length=24)
    # Diagnostic, not an externally certified content correctness claim.
    reviewer_signature_verified_here: Literal[False] = False
    correct_answer_independently_established_here: Literal[False] = False


class ExamBlueprintReview(StrictContract):
    schema_version: Literal["jr.jrei.exam-blueprint-review-result.v1"] = (
        "jr.jrei.exam-blueprint-review-result.v1"
    )
    policy_version: Identifier
    request_sha256: Digest
    blueprint_id: Identifier
    blueprint_revision: Identifier
    declared_item_count: int
    eligible_candidate_count: int
    covered_domain_counts: dict[str, int]
    required_domain_counts: dict[str, int]
    missing_domain_counts: dict[str, int]
    findings: list[ItemIntegrityFinding]
    duplicate_stem_groups: list[list[Identifier]]
    decision: Literal[
        "HOLD_INVALID_BLUEPRINT_OR_COUNTS",
        "HOLD_KEY_RIGHTS_PROVENANCE_OR_DUPLICATES",
        "CANDIDATE_FOR_INDEPENDENT_EXAM_AUTHORITY",
    ]
    reasons: list[str]
    original_exam_authority: Literal["PHP_MOTHER_DB_ONLY"] = "PHP_MOTHER_DB_ONLY"
    student_answer_data_accessed: Literal[False] = False
    applicant_entitlement_checked: Literal[False] = False
    answer_key_verified_by_service: Literal[False] = False
    testly_humanability_validated: Literal[False] = False
    items_created: Literal[False] = False
    timed_exam_activated: Literal[False] = False
    exam_published: Literal[False] = False
    sale_or_payment_executed: Literal[False] = False


def review_exam_blueprint(request: ExamReviewRequest) -> ExamBlueprintReview:
    blueprint = request.blueprint
    per_item: dict[str, set[str]] = {i.item_id: set() for i in request.items}
    stems: dict[str, list[str]] = {}
    domains: Counter[str] = Counter()
    for item in request.items:
        reasons = per_item[item.item_id]
        if (item.blueprint_id != blueprint.blueprint_id or
                item.blueprint_revision != blueprint.revision_id):
            reasons.add("BLUEPRINT_REVISION_MISMATCH")
        if item.domain_code not in blueprint.domain_required_counts:
            reasons.add("DOMAIN_NOT_IN_BLUEPRINT")
        if blueprint.language != "bi" and item.language != blueprint.language:
            reasons.add("LANGUAGE_NOT_IN_BLUEPRINT")
        if item.source_withdrawn or item.source_rights_state in ("REVOKED", "RESTRICTED"):
            reasons.add("SOURCE_WITHDRAWN_OR_RESTRICTED")
        elif item.source_rights_state != "ALLOWED":
            reasons.add("SOURCE_RIGHTS_NOT_REVIEWED_FOR_USE")
        if not item.source_version_current or not item.independently_source_reviewed:
            reasons.add("CURRENT_SOURCE_REVISION_NOT_INDEPENDENTLY_REVIEWED")
        if not item.independently_item_reviewed:
            reasons.add("EXAM_ITEM_SCIENTIFIC_REVIEW_MISSING")
        if (len(item.independent_key_review_receipt_sha256s) <
                blueprint.required_key_reviewers):
            reasons.add("INSUFFICIENT_INDEPENDENT_KEY_REVIEWERS")
        if not item.key_provenance_verified_by_original_authority:
            reasons.add("ORIGINAL_AUTHORITY_HAS_NOT_VERIFIED_KEY")
        if not item.answer_rationale_sha256 or not item.key_evidence_sha256:
            reasons.add("ANSWER_RATIONALE_OR_KEY_EVIDENCE_MISSING")
        if blueprint.require_original_items and not item.original_item:
            reasons.add("ORIGINAL_ITEM_REQUIREMENT_NOT_MET")
        if blueprint.requires_accommodation_review and not item.accommodation_reviewed:
            reasons.add("ACCESSIBILITY_ACCOMMODATION_REVIEW_MISSING")
        stems.setdefault(item.item_stem_sha256, []).append(item.item_id)
        domains[item.domain_code] += 1

    duplicate_groups: list[list[str]] = []
    for group in stems.values():
        if len(group) > 1:
            ids = sorted(group)
            duplicate_groups.append(ids)
            for item_id in ids:
                per_item[item_id].add("DUPLICATE_STEM_FINGERPRINT")
    duplicate_groups.sort(key=lambda group: group[0])
    coverage = {domain: domains.get(domain, 0)
                for domain in sorted(blueprint.domain_required_counts)}
    missing = {
        domain: max(0, required - domains.get(domain, 0))
        for domain, required in sorted(blueprint.domain_required_counts.items())
    }
    findings = [
        ItemIntegrityFinding(
            item_id=i.item_id,
            decision="HOLD" if per_item[i.item_id] else "CANDIDATE_FOR_OWNER_REVIEW",
            reason_codes=sorted(per_item[i.item_id]) if per_item[i.item_id]
            else ["CALLER_SUPPLIED_REVIEWS_NOT_INDEPENDENTLY_AUTHENTICATED"],
        ) for i in sorted(request.items, key=lambda i: i.item_id)
    ]
    held = sum(f.decision == "HOLD" for f in findings)
    reasons: list[str] = ["CALLER_SUPPLIED_RIGHTS_AND_REVIEW_METADATA_UNATTESTED"]
    if not request.blueprint_independently_approved:
        reasons.append("BLUEPRINT_AUTHORITY_NOT_INDEPENDENTLY_APPROVED")
    if len(request.items) != blueprint.required_item_count or any(missing.values()) or any(
        domains[k] > blueprint.domain_required_counts.get(k, 0) for k in domains
    ):
        reasons.append("BLUEPRINT_DISTRIBUTION_OR_COUNT_MISMATCH")
        decision = "HOLD_INVALID_BLUEPRINT_OR_COUNTS"
    elif held or not request.blueprint_independently_approved:
        reasons.append("ITEM_OR_REVIEW_REQUIREMENTS_NOT_MET")
        decision = "HOLD_KEY_RIGHTS_PROVENANCE_OR_DUPLICATES"
    else:
        reasons.append("ORIGINAL_MOTHER_DB_AUTHORITY_MUST_REVALIDATE_AND_APPROVE")
        decision = "CANDIDATE_FOR_INDEPENDENT_EXAM_AUTHORITY"

    raw = json.dumps(request.model_dump(mode="json"), ensure_ascii=False,
                     sort_keys=True, separators=(",", ":")).encode("utf-8")
    return ExamBlueprintReview(
        policy_version=request.policy_version,
        request_sha256=hashlib.sha256(raw).hexdigest(),
        blueprint_id=blueprint.blueprint_id,
        blueprint_revision=blueprint.revision_id,
        declared_item_count=len(request.items),
        eligible_candidate_count=len(request.items)-held,
        covered_domain_counts=coverage,
        required_domain_counts=dict(sorted(blueprint.domain_required_counts.items())),
        missing_domain_counts=missing,
        findings=findings,
        duplicate_stem_groups=duplicate_groups,
        decision=decision,
        reasons=sorted(set(reasons)),
    )
