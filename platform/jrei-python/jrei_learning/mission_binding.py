"""Bind a metacognitive decision to the EXISTING scoped mission DAG contract.

The result is a reviewable non-executable mission PROPOSAL, never a live job,
signed worker lease, source approval, knowledge promotion or model update.
"""
from __future__ import annotations

from typing import Literal

from pydantic import model_validator

from jrei_core.contracts import (
    Digest, Identifier, MissionNode, MissionProposal, MissionRequest, StrictContract,
)
from jrei_core.mission import propose_mission
from jrei_learning.metacognitive_cycle import (
    LearningDecision, MetacognitiveCycleRequest, plan_metacognitive_cycle,
)


class LearningMissionBindingRequest(StrictContract):
    schema_version: Literal["jr.jrei.metacognitive-mission-binding.v1"] = (
        "jr.jrei.metacognitive-mission-binding.v1"
    )
    mission_id: Identifier
    policy_digest: Digest
    target_gap_id: Identifier
    cycle: MetacognitiveCycleRequest

    @model_validator(mode="after")
    def target_is_observed(self) -> "LearningMissionBindingRequest":
        if self.target_gap_id not in {x.gap_id for x in self.cycle.gaps.gaps}:
            raise ValueError("TARGET_GAP_NOT_IN_AGGREGATE")
        return self


class LearningMissionBinding(StrictContract):
    schema_version: Literal["jr.jrei.metacognitive-mission-binding-result.v1"] = (
        "jr.jrei.metacognitive-mission-binding-result.v1"
    )
    target_gap_id: Identifier
    next_learning_action: str
    learning_decision: LearningDecision
    proposal: MissionProposal
    original_owner_authority_required: Literal[True] = True
    mission_submitted: Literal[False] = False
    worker_lease_issued: Literal[False] = False
    rights_granted: Literal[False] = False
    independent_review_completed: Literal[False] = False
    improvement_proven: Literal[False] = False


# Kinds are constrained by original jrei_core.contracts.MissionNode + JS
# jrei-scoped-mission-planner.mjs, not text generated by an LLM.
_REVIEW_GRAPH: dict[str, tuple[str, ...]] = {
    "REQUEST_SOURCE_RIGHTS_REVIEW": ("RIGHTS_REVIEW",),
    "REPAIR_SOURCE_PROVENANCE": (
        "RIGHTS_REVIEW", "PUBLIC_SOURCE_DISCOVERY", "EVIDENCE_INDEX_PROPOSAL",
    ),
    "OBTAIN_INDEPENDENT_EVIDENCE_REVIEW": (
        "RIGHTS_REVIEW", "EDUCATIONAL_RESPONSE_REVIEW",
    ),
    "REVISE_OR_REJECT_CHALLENGER": ("EDUCATIONAL_RESPONSE_REVIEW",),
    "CURATE_PAIRED_BILINGUAL_HELDOUT": ("EDUCATIONAL_RESPONSE_REVIEW",),
    "DESIGN_BOUNDED_EXPERIMENT": (
        "EVIDENCE_INDEX_PROPOSAL", "EDUCATIONAL_RESPONSE_REVIEW",
    ),
    "REQUEST_OWNER_SCIENTIFIC_DECISION": ("EDUCATIONAL_RESPONSE_REVIEW",),
}


def bind_learning_mission(request: LearningMissionBindingRequest) -> LearningMissionBinding:
    cycle = plan_metacognitive_cycle(request.cycle)
    matched = next(x for x in cycle.decisions if x.gap_id == request.target_gap_id)
    steps = _REVIEW_GRAPH[matched.next_action]
    nodes: list[MissionNode] = []
    for i, kind in enumerate(steps):
        identifier = "meta.step." + str(i + 1).zfill(2)
        dependency = [nodes[-1].id] if nodes else []
        nodes.append(MissionNode(id=identifier, kind=kind, after=dependency))
    plan = propose_mission(MissionRequest(
        mission_id=request.mission_id,
        policy_digest=request.policy_digest,
        nodes=nodes,
    ))
    return LearningMissionBinding(
        target_gap_id=matched.gap_id,
        next_learning_action=matched.next_action,
        learning_decision=matched,
        proposal=plan,
    )
